import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import {
  loadCoreLocale,
  evaluateObject,
  placeholdersMatch,
  postGeneratedOverrideModulePaths,
  preGeneratedOverrideModulePaths,
  renderLocaleObject
} from './i18n-utils.mjs'
import generatedOverrides from '../src/locales/generated-locale-overrides.js'

const root = resolve(process.cwd())
const langDir = join(root, 'src', 'locales', 'lang')
const outputPath = join(root, 'src', 'locales', 'generated-locale-overrides.js')
const translatedLocales = [
  'ar-SA',
  'de-DE',
  'fr-FR',
  'ja-JP',
  'ko-KR',
  'ru-RU',
  'th-TH',
  'vi-VN'
]

const modules = await Promise.all(
  [...preGeneratedOverrideModulePaths, ...postGeneratedOverrideModulePaths]
    .map(modulePath => import(new URL(modulePath, import.meta.url)))
)

function effectiveLocale(localeName) {
  return Object.assign(
    {},
    loadCoreLocale(langDir, localeName).locale,
    ...modules.map(module => module.default?.[localeName] || {}),
    generatedOverrides[localeName] || {}
  )
}

const english = effectiveLocale('en-US')
const outputMessages = structuredClone(generatedOverrides)
const generatedSource = readFileSync(outputPath, 'utf8')
const verifiedSameTranslations = evaluateObject(
  generatedSource,
  'export const verifiedSameTranslations =',
  'generated-locale-overrides.js'
)

for (const localeName of translatedLocales) {
  const locale = effectiveLocale(localeName)
  const candidatesBySource = new Map()

  for (const [key, source] of Object.entries(english)) {
    const target = locale[key]
    if (
      typeof source !== 'string' ||
      typeof target !== 'string' ||
      target === source ||
      !placeholdersMatch(source, target)
    ) continue

    const counts = candidatesBySource.get(source) || new Map()
    counts.set(target, (counts.get(target) || 0) + 1)
    candidatesBySource.set(source, counts)
  }

  let reusable = 0
  let ambiguous = 0
  for (const [key, source] of Object.entries(english)) {
    const target = locale[key]
    if (typeof source !== 'string' || (target !== undefined && target !== source)) continue
    const counts = candidatesBySource.get(source)
    if (!counts?.size) continue
    const ranked = [...counts.entries()].sort((left, right) => right[1] - left[1])
    if (ranked.length > 1 && ranked[0][1] === ranked[1][1]) {
      ambiguous += 1
      continue
    }
    outputMessages[localeName] ||= {}
    outputMessages[localeName][key] = ranked[0][0]
    reusable += 1
  }

  console.log(`${localeName}: ${reusable} reusable translations, ${ambiguous} ambiguous`)
}

function renderGeneratedOverrides(messages, verifiedSame) {
  const renderedMessages = Object.entries(messages)
    .map(([localeName, locale]) => {
      const body = renderLocaleObject(locale)
        .split('\n')
        .map(line => `    ${line.trimStart()}`)
        .join('\n')
      return `  ${JSON.stringify(localeName)}: {\n${body}\n  }`
    })
    .join(',\n')
  const renderedVerified = Object.entries(verifiedSame)
    .map(([localeName, keys]) => (
      `  ${JSON.stringify(localeName)}: ${JSON.stringify([...keys].sort())}`
    ))
    .join(',\n')

  return `// Generated by scripts/translate-incomplete-locales.mjs.\n` +
    `// Machine-generated strings are reviewed by placeholder and completeness audits.\n` +
    `const messages = {\n${renderedMessages}\n}\n\n` +
    `export const verifiedSameTranslations = {\n${renderedVerified}\n}\n\n` +
    `export default messages\n`
}

writeFileSync(
  outputPath,
  renderGeneratedOverrides(outputMessages, verifiedSameTranslations),
  'utf8'
)
